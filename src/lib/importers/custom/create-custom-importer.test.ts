import { describe, it, expect } from 'vitest';
import BigNumber from 'bignumber.js';
import { createCustomImporter } from '$lib/importers/custom/create-custom-importer';
import type { CustomImporterConfig, IExchangeImporter, RowKind } from '$lib/types';

const bn = (n: string) => new BigNumber(n);

const HEADER = 'When,Kind,Coin,Qty,Unit Price,Total,Ccy,Fee,Ref,Memo';

const baseConfig = (overrides: Partial<CustomImporterConfig> = {}): CustomImporterConfig => ({
  schemaVersion: 1,
  id: 'test-ex',
  name: 'Test Exchange',
  header: { mode: 'auto' },
  requiredColumns: ['When', 'Kind', 'Coin', 'Qty'],
  delimiter: ',',
  decimalSeparator: '.',
  dateFormats: ['iso'],
  timezone: 'utc',
  columns: {
    date: 'When', type: 'Kind', asset: 'Coin', amount: 'Qty',
    total: 'Total', fee: 'Fee', txId: 'Ref', notes: 'Memo',
  },
  type: {
    mode: 'column',
    rules: [
      { match: 'equals', value: 'bought', kind: 'buy' },
      { match: 'equals', value: 'sold', kind: 'sell' },
      { match: 'startsWith', value: 'in', kind: 'transfer-in' },
      { match: 'contains', value: 'withdraw', kind: 'transfer-out' },
      { match: 'equals', value: 'skip me', kind: 'ignore' },
    ],
  },
  quoteCurrency: { mode: 'column', column: 'Ccy' },
  feeCurrency: { mode: 'quote' },
  preprocessors: [],
  ...overrides,
});

interface RowValues {
  when?: string; kind?: string; coin?: string; qty?: string; price?: string;
  total?: string; ccy?: string; fee?: string; ref?: string; memo?: string;
}

const row = (v: RowValues = {}) =>
  [
    v.when ?? '2020-08-14T11:12:13Z', v.kind ?? 'bought', v.coin ?? 'ETH', v.qty ?? '1.75',
    v.price ?? '', v.total ?? '', v.ccy ?? '', v.fee ?? '', v.ref ?? '', v.memo ?? '',
  ].join(',');

const csv = (...rows: string[]) => [HEADER, ...rows].join('\n');

const parseOne = (config: CustomImporterConfig, values: RowValues) =>
  createCustomImporter(config).parse(csv(row(values)))[0];

const withKind = (kind: RowKind) => baseConfig({ type: { mode: 'fixed', kind } });

describe('createCustomImporter', () => {
  const importer: IExchangeImporter = createCustomImporter(baseConfig());

  it('uses the config name as exchangeName', () => {
    expect(importer.exchangeName).toBe('Test Exchange');
  });

  describe('detect()', () => {
    it('matches when every required column is present', () => {
      expect(importer.detect(HEADER)).toBe(true);
    });

    it('matches with a preamble before the header in auto mode', () => {
      expect(importer.detect(['Report', 'Generated by something', HEADER].join('\n'))).toBe(true);
    });

    it('does not match when a required column is missing', () => {
      expect(importer.detect('When,Kind,Coin')).toBe(false);
    });

    it('does not match empty input', () => {
      expect(importer.detect('')).toBe(false);
    });
  });

  describe('parse()', () => {
    it('throws on empty input', () => {
      expect(() => importer.parse('  ')).toThrow('CSV is empty');
    });

    it('throws when required columns are missing', () => {
      expect(() => importer.parse('When,Kind\n2020-01-01T00:00:00Z,bought')).toThrow(/Missing required columns: Coin, Qty/);
    });

    it('maps a fiat-quoted buy: quote paid → asset received, value kept', () => {
      const tx = parseOne(baseConfig(), { total: '913.40', ccy: 'EUR', fee: '2.10', ref: 'r-77' });
      expect(tx).toMatchObject({
        id: 'test-ex-r-77-0',
        type: 'buy',
        date: new Date('2020-08-14T11:12:13Z'),
        fromAsset: 'EUR', fromAmount: bn('913.40'),
        toAsset: 'ETH', toAmount: bn('1.75'),
        feeAsset: 'EUR', feeAmount: bn('2.10'),
        fiatCurrency: 'EUR', fiatValue: bn('913.40'),
        exchange: 'Test Exchange',
      });
    });

    it('maps a sell as the mirror of a buy', () => {
      const tx = parseOne(baseConfig(), { kind: 'sold', qty: '-0.4', total: '377.15', ccy: 'USD' });
      expect(tx).toMatchObject({
        type: 'sell',
        fromAsset: 'ETH', fromAmount: bn('0.4'),
        toAsset: 'USD', toAmount: bn('377.15'),
        fiatCurrency: 'USD', fiatValue: bn('377.15'),
      });
    });

    it('turns a crypto-quoted buy into a trade, keeping the quote value and ticker', () => {
      const tx = parseOne(baseConfig(), { total: '0.061', ccy: 'BTC' });
      expect(tx).toMatchObject({
        type: 'trade',
        fromAsset: 'BTC', fromAmount: bn('0.061'),
        toAsset: 'ETH', toAmount: bn('1.75'),
        fiatCurrency: 'BTC', fiatValue: bn('0.061'),
      });
    });

    it('turns a stablecoin-quoted sell into a trade and keeps the stablecoin ticker', () => {
      const tx = parseOne(baseConfig(), { kind: 'sold', total: '2410.5', ccy: 'USDT' });
      expect(tx).toMatchObject({ type: 'trade', toAsset: 'USDT', fiatCurrency: 'USDT', fiatValue: bn('2410.5') });
    });

    it('keeps a buy paid in a fiat Frankfurter cannot convert as a buy', () => {
      const tx = parseOne(baseConfig(), { total: '183000', ccy: 'ARS' });
      expect(tx).toMatchObject({ type: 'buy', fromAsset: 'ARS', fiatCurrency: 'ARS', fiatValue: bn('183000') });
    });

    it('computes the value from amount × price when there is no total column', () => {
      const config = baseConfig({ columns: { ...baseConfig().columns, total: undefined, price: 'Unit Price' } });
      const tx = parseOne(config, { qty: '2', price: '150.25', ccy: 'GBP' });
      expect(tx.fiatValue).toEqual(bn('300.5'));
      expect(tx.fromAmount).toEqual(bn('300.5'));
    });

    it('leaves the value unset (for enrichment) when the total is blank or zero', () => {
      const blank = parseOne(baseConfig(), { ccy: 'EUR' });
      const zero = parseOne(baseConfig(), { total: '0', ccy: 'EUR' });
      [blank, zero].forEach((tx) => {
        expect(tx.fiatValue).toBeUndefined();
        expect(tx.fromAsset).toBeUndefined();
        expect(tx).toMatchObject({ type: 'buy', toAsset: 'ETH', toAmount: bn('1.75') });
      });
    });

    it('keeps the quote currency as written in the file (it is part of the dedup key)', () => {
      const tx = parseOne(baseConfig(), { total: '10', ccy: 'eur' });
      expect(tx).toMatchObject({ fromAsset: 'eur', fiatCurrency: 'eur', type: 'buy' });
    });

    it('uses a fixed quote currency', () => {
      const tx = parseOne(baseConfig({ quoteCurrency: { mode: 'fixed', value: 'CHF' } }), { total: '50' });
      expect(tx).toMatchObject({ fromAsset: 'CHF', fiatCurrency: 'CHF', fiatValue: bn('50') });
    });

    it('reads a currency embedded in the money cells', () => {
      const config = baseConfig({ quoteCurrency: { mode: 'embedded' }, feeCurrency: { mode: 'embedded' } });
      const tx = parseOne(config, { total: '"$1,204.55"', fee: '3.10 DKK' });
      expect(tx).toMatchObject({
        fromAsset: 'USD', fromAmount: bn('1204.55'), fiatCurrency: 'USD',
        feeAsset: 'DKK', feeAmount: bn('3.10'),
      });
    });

    it('can charge the fee in the asset itself', () => {
      const tx = parseOne(baseConfig({ feeCurrency: { mode: 'asset' } }), { fee: '0.002' });
      expect(tx).toMatchObject({ feeAsset: 'ETH', feeAmount: bn('0.002') });
    });

    it('omits a blank or zero fee', () => {
      expect(parseOne(baseConfig(), { fee: '0', ccy: 'EUR' }).feeAmount).toBeUndefined();
      expect(parseOne(baseConfig(), { ccy: 'EUR' }).feeAmount).toBeUndefined();
    });

    it.each<[RowKind, 'from' | 'to', string]>([
      ['transfer-in', 'to', 'transfer'],
      ['transfer-out', 'from', 'transfer'],
      ['staking', 'to', 'staking'],
      ['mining', 'to', 'mining'],
      ['airdrop', 'to', 'airdrop'],
      ['fee', 'from', 'fee'],
      ['trade-out', 'from', 'trade'],
    ])('maps %s to the %s side as type %s', (kind, side, type) => {
      const tx = parseOne(withKind(kind), { total: '61.2', ccy: 'EUR' });
      expect(tx.type).toBe(type);
      expect(side === 'to' ? tx.toAsset : tx.fromAsset).toBe('ETH');
      expect(side === 'to' ? tx.fromAsset : tx.toAsset).toBeUndefined();
      expect(tx.fiatValue).toEqual(bn('61.2'));
    });

    it('derives transfer direction from the sign with transfer-by-sign', () => {
      const config = withKind('transfer-by-sign');
      expect(parseOne(config, { qty: '-3' })).toMatchObject({ type: 'transfer', fromAsset: 'ETH', fromAmount: bn('3') });
      expect(parseOne(config, { qty: '3' })).toMatchObject({ type: 'transfer', toAsset: 'ETH', toAmount: bn('3') });
    });

    it('matches type rules case-insensitively with equals, startsWith and contains', () => {
      expect(parseOne(baseConfig(), { kind: ' BOUGHT ' }).type).toBe('buy');
      expect(parseOne(baseConfig(), { kind: 'Incoming' }).toAsset).toBe('ETH');
      expect(parseOne(baseConfig(), { kind: 'Crypto withdrawal' }).fromAsset).toBe('ETH');
    });

    it('drops ignored rows', () => {
      const txs = importer.parse(csv(row({ kind: 'skip me', qty: '' }), row()));
      expect(txs).toHaveLength(1);
      expect(txs[0].id).toBe('test-ex-row-1');
    });

    it('uses the fallback kind for unmatched type values', () => {
      const config = baseConfig({ type: { mode: 'column', rules: [], fallback: 'transfer-out' } });
      expect(parseOne(config, { kind: 'whatever' })).toMatchObject({ type: 'transfer', fromAsset: 'ETH' });
    });

    it('throws with the row number on an unmatched type value without fallback', () => {
      expect(() => importer.parse(csv(row(), row({ kind: 'mystery' }))))
        .toThrow('Row 2: Unrecognized type "mystery"');
    });

    it('throws with the row number on a bad date', () => {
      expect(() => importer.parse(csv(row({ when: 'not a date' })))).toThrow(/^Row 1: Unrecognized date/);
    });

    it('builds notes from the notes column and prefix, omitting blanks', () => {
      const config = baseConfig({ notesPrefix: 'memo: ' });
      expect(parseOne(config, { memo: 'gift' }).notes).toBe('memo: gift');
      expect(parseOne(config, {}).notes).toBeUndefined();
    });

    it('treats optional mapped columns missing from the file as blank', () => {
      const tx = createCustomImporter(baseConfig()).parse('When,Kind,Coin,Qty\n2020-08-14T11:12:13Z,bought,SOL,4');
      expect(tx[0]).toMatchObject({ type: 'buy', toAsset: 'SOL', toAmount: bn('4') });
      expect(tx[0].fiatValue).toBeUndefined();
    });

    it('supports comma decimals and semicolon delimiters', () => {
      const config = baseConfig({ delimiter: ';', decimalSeparator: ',' });
      const text = [HEADER.replaceAll(',', ';'), '2020-08-14T11:12:13Z;bought;ETH;1,5;;1.234,50;EUR;;;'].join('\n');
      expect(createCustomImporter(config).parse(text)[0]).toMatchObject({
        toAmount: bn('1.5'), fiatValue: bn('1234.50'),
      });
    });
  });

  it('resolves preprocessors by id', () => {
    const withPre = createCustomImporter(baseConfig({ preprocessors: ['reclassify-inbound-as-buys'] }));
    expect(withPre.preprocessors.map((p) => p.id)).toEqual(['reclassify-inbound-as-buys']);
  });
});
